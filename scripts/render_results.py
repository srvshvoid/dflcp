"""Render a transparent synthetic replay index from run directories.

This report generator never turns a smoke replay into a benchmark.  It writes
only provenance and raw recorded values, labels every run synthetic/unverified,
and includes a pending section when real experiments do not exist.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def _read_json(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        value = json.load(handle)
    if not isinstance(value, dict):
        raise ValueError(f"{path} must contain an object")
    return value


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        return []
    rows: list[dict[str, Any]] = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                value = json.loads(line)
                if isinstance(value, dict):
                    rows.append(value)
    return rows


def render_results(runs_root: Path | str, output: Path | str) -> Path:
    """Write a markdown replay index from actual run artifacts."""

    root = Path(runs_root)
    destination = Path(output)
    rows: list[str] = [
        "# FedForge generated replay index",
        "",
        "> **Synthetic / unverified only.** This file is generated from local",
        "> run directories and is not a research results table. No real dataset",
        "> result is present until its verification and experiment gates pass.",
        "",
        "| Run directory | Run id | Seed | Git commit | Rounds recorded | Evidence |",
        "| --- | --- | ---: | --- | ---: | --- |",
    ]
    found = False
    if root.is_dir():
        for run_dir in sorted(path for path in root.iterdir() if path.is_dir()):
            provenance_path = run_dir / "provenance.json"
            if not provenance_path.is_file():
                continue
            found = True
            provenance = _read_json(provenance_path)
            metrics = _read_jsonl(run_dir / "metrics.jsonl")
            rows.append(
                "| `{}` | `{}` | `{}` | `{}` | {} | synthetic-unverified |".format(
                    run_dir.as_posix(),
                    provenance.get("run_id", run_dir.name),
                    provenance.get("seed", "unknown"),
                    provenance.get("git_commit", "unknown"),
                    len(metrics),
                )
            )
    if not found:
        rows.append("| — | — | — | — | 0 | pending |")
    rows.extend(
        [
            "",
            "## Pending research evidence",
            "",
            "- Real licensed dataset facts, disjoint manifests, and preprocessing counts.",
            "- CNN/ViT GPU runs, calibration, cross-generator evaluation, and confidence intervals.",
            "- Flower SecAgg+ / DP measurements and production service evidence.",
            "- Attack/defense results with honest-client rejection costs.",
            "",
            "Generated by `scripts/render_results.py`; inspect each run's",
            "`provenance.json` and `metrics.jsonl` before citing anything.",
            "",
        ]
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(rows), encoding="utf-8")
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="runs")
    parser.add_argument("--output", default="docs/RESULTS.generated.md")
    args = parser.parse_args()
    print(render_results(args.runs, args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
